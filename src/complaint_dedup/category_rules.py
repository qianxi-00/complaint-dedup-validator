def canonical_category(value: str | None) -> str | None:
    """把原始分类归一为规范分类；空值返回 None。"""
    text = str(value or "").strip()
    if not text:
        return None
    text = _CATEGORY_PREFIX_RE.sub("", text)
    text = _REGION_PREFIX_RE.sub("", text)
    text = re.sub(r"\s+", "", text)
    if not text:
        return None
    return CATEGORY_ALIASES.get(text, text)


def problem_family_for(canonical: str | None) -> str | None:
    """由规范分类得到问题族；未知分类回退为规范分类本身（族内互斥）。"""
    text = str(canonical or "").strip()
    if not text:
        return None
    for family, keywords in PROBLEM_FAMILY_KEYWORDS:
        if any(keyword in text for keyword in keywords):
            return family
    return text
